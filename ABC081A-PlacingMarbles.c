#include <stdio.h>

#define N 3

int main(void)
{
  int box[N], count = 0;
  scanf("%1d%1d%1d", &box[0], &box[1], &box[2]);

  for (int i = 0; i < N; i++)
    if (box[i] == 1)
      count++;

  printf("%d\n", count);

  return 0;
}
